const { openImageManager } = require('./browser_projects.cjs');
/* Node 22+, Chromium CDP, serve_library_fixture.py; simulated images only. */
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const [debugURL, appURL, output] = process.argv.slice(2);
if (!debugURL || !appURL || !output) throw Error('Expected DEBUG_URL APP_URL OUTPUT_DIR');
(async()=>{
  fs.mkdirSync(output,{recursive:true});
  const target=await(await fetch(debugURL+'/json/new?about:blank',{method:'PUT'})).json();
  const ws=new WebSocket(target.webSocketDebuggerUrl);
  await new Promise(r=>ws.addEventListener('open',r,{once:true}));
  let id=0;const pending=new Map(),errors=[];
  const send=(method,params={})=>new Promise((resolve,reject)=>{
    const key=++id,timer=setTimeout(()=>{pending.delete(key);reject(Error('Timeout '+method));},15000);
    pending.set(key,{resolve,reject,timer});ws.send(JSON.stringify({id:key,method,params}));
  });
  ws.addEventListener('message',event=>{
    const m=JSON.parse(event.data),p=pending.get(m.id);
    if(p){clearTimeout(p.timer);pending.delete(m.id);m.error?p.reject(Error(JSON.stringify(m.error))):p.resolve(m.result);}
    if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails.exception?.description||m.params.exceptionDetails.text);
    if(m.method==='Page.javascriptDialogOpening')void send('Page.handleJavaScriptDialog',{accept:true});
  });
  const evaluate=async expression=>{const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(r.exceptionDetails.exception?.description||r.exceptionDetails.text);return r.result.value;};
  const wait=async expression=>{for(let i=0;i<150;i++){if(await evaluate(expression))return;await new Promise(r=>setTimeout(r,100));}throw Error('Condition not met: '+expression+'; '+await evaluate('document.querySelector("#toast")?.textContent'));};
  const click=async selector=>{const p=await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.scrollIntoView({block:'nearest'});const r=e.getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()`);for(const type of ['mousePressed','mouseReleased'])await send('Input.dispatchMouseEvent',{type,...p,button:'left',clickCount:1});};
  const input=(selector,value)=>evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event(e.tagName==='SELECT'?'change':'input',{bubbles:true}))})()`);
  const shot=async name=>{const r=await send('Page.captureScreenshot');fs.writeFileSync(path.join(output,name),Buffer.from(r.data,'base64'));};
  const jobDone=()=>wait('document.querySelector("#start-image-job") && !document.querySelector("#start-image-job").closest("fieldset").disabled');
  const openImages=async()=>{await openImageManager(evaluate,wait,click);await jobDone();};
  const card=reference=>'.device-card[data-image='+JSON.stringify(reference)+']';
  const count=kind=>evaluate(`Number(document.querySelector('[data-category="${kind}"] .category-count').textContent)`);
  const expandAll=async()=>{
    for(let batch=0;batch<10;batch++){
      if(!await evaluate('!!document.querySelector(".library-more")'))return;
      const before=await evaluate('document.querySelectorAll(".device-card").length');
      await click('.library-more');
      await wait('document.querySelectorAll(".device-card").length>'+before);
    }
    throw Error('Library pagination did not reach its last page');
  };
  try{
    await send('Page.enable');await send('Runtime.enable');
    await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
    await send('Page.navigate',{url:appURL});
    await wait('!!document.querySelector("#library-home") && !document.querySelector("#access-dialog")?.open');
    assert.deepEqual(await evaluate('Array.from(document.querySelectorAll("[data-category]")).map(e=>e.dataset.category)'),['router','switch','host','firewall']);
    assert.equal(await evaluate('document.querySelectorAll(".device-card,[data-device-group],#manage-images,.library-note").length'),0,'home contains categories only');
    assert.equal(await evaluate('new Set(Array.from(document.querySelectorAll("[data-category]")).map(e=>e.getBoundingClientRect().top)).size'),1,'four categories stay horizontal');
    await shot('device-categories.png');
    await click('[data-category=router]');
    await wait('document.querySelectorAll("[data-device-group=router] .device-card").length===60');
    assert.equal(await evaluate('document.querySelectorAll(".library input[type=search],#device-search,.library-search").length'),0,'category contains no search field');
    assert.equal(await evaluate('document.querySelectorAll("[data-device-group]").length'),1);
    const routerCount=await count('router'), hostCount=await count('host');
    const nav=await evaluate('document.querySelector(".device-category-nav").getBoundingClientRect().top');
    const cards=await evaluate('Array.from(document.querySelectorAll(".device-card")).slice(0,2).map(e=>({top:e.getBoundingClientRect().top,left:e.getBoundingClientRect().left}))');
    assert.equal(cards[0].top,cards[1].top);assert.ok(cards[0].left<cards[1].left,'devices use a horizontal grid');
    await click('.library-more');
    await wait('document.querySelectorAll(".device-card").length===120');
    assert.equal(await evaluate('document.querySelector(".device-category-nav").getBoundingClientRect().top'),nav,'category navigation remains visible when scrolling');
    await expandAll();
    assert.equal(await evaluate('document.querySelectorAll(".device-card").length'),routerCount,'pagination exposes every router');
    assert.equal(await evaluate(`document.querySelector(${JSON.stringify(card('fixture/router-199:latest'))})?.querySelector('b').textContent`),'测试路由器 199','last fixture device is reachable without search');
    await click('[data-category=host]');
    await wait('!!document.querySelector("[data-device-group=host] .device-card")');
    assert.equal(await evaluate('document.querySelectorAll(".device-card").length'),hostCount);
    assert.equal(await evaluate('document.querySelectorAll("[data-device-group=router]").length'),0,'switching category removes the previous category');
    assert.equal(await evaluate('document.querySelector("#device-library").scrollTop'),0,'changing category resets list scroll');
    await click('#library-back');
    await wait('!!document.querySelector("#library-home")');
    assert.equal(await evaluate('document.activeElement.dataset.category'),'host','back returns focus to the category');
    for (const key of ['ArrowRight','Home','End','ArrowLeft']) {
      await send('Input.dispatchKeyEvent',{type:'keyDown',key});await send('Input.dispatchKeyEvent',{type:'keyUp',key});
      const selected=key==='ArrowRight'||key==='End'?'firewall':key==='Home'?'router':'host';
      await wait('document.activeElement.dataset.category==='+JSON.stringify(selected));
      assert.equal(await evaluate('document.activeElement.getAttribute("aria-pressed")'),'true');
    }
    await click('[data-category=router]');
    await wait('document.querySelectorAll(".device-card").length===60');
    assert.equal(await evaluate('document.querySelector("#device-library").scrollTop'),0,'returning to a category resets pagination and scroll');
    await shot('device-grid.png');
    await openImages();
    assert.deepEqual(await evaluate('Array.from(document.querySelector("#image-template").options).map(o=>o.value)'),['','frr','linux-bridge','linux-host','linux-firewall']);
    await input('#image-search','alpine/frr:latest');
    await click('.image-entry[data-image="alpine/frr:latest"] .image-delete');
    await wait(`!document.querySelector('.image-entry[data-image="alpine/frr:latest"]')`);
    await jobDone();await click('#close-images');
    await wait(`Number(document.querySelector('[data-category=router] .category-count').textContent)===${routerCount-1}`);
    await expandAll();
    assert.equal(await evaluate(`document.querySelectorAll(${JSON.stringify(card('alpine/frr:latest'))}).length`),0,'removed default image has no card on any page');
    assert.equal(await evaluate('document.querySelectorAll(".device-card").length'),routerCount-1,'only the removed image leaves the category');
    await openImages();
    await input('#image-search','');
    await input('#image-address','fixture/firewall:latest');await input('#image-title','边界防火墙');await input('#image-template','linux-firewall');
    await click('#start-image-job');
    await wait(`!!document.querySelector('.image-entry[data-image="fixture/firewall:latest"]')`);
    await jobDone();await click('#close-images');await click('[data-category=firewall]');
    await wait('document.querySelectorAll("[data-device-group=firewall] .device-card").length===1');
    assert.equal(await evaluate(`document.querySelector(${JSON.stringify(card('fixture/firewall:latest'))})?.querySelector('b').textContent`),'边界防火墙');
    await click(card('fixture/firewall:latest'));
    await wait('!!document.querySelector(".topology-node[data-node=fw1]")');
    await openImages();await input('#image-search','fixture/firewall:latest');
    await click('.image-entry[data-image="fixture/firewall:latest"] .image-settings');
    await input('#edit-image-template','linux-host');await input('#edit-image-title','测试 PC');await click('#save-image-settings');
    await wait('!document.querySelector("#image-edit-form")');
    await click('#close-images');
    assert.equal(await evaluate('document.querySelector("[data-category=firewall]").getAttribute("aria-pressed")'),'true','catalog refresh preserves category');
    await wait('document.querySelectorAll("[data-device-group=firewall] .device-card").length===0');
    assert.equal(await count('firewall'),0,'reclassification removes the firewall card');
    await click('[data-category=host]');
    await wait(`document.querySelectorAll('[data-device-group=host] .device-card').length===${hostCount+1}`);
    assert.equal(await evaluate(`document.querySelector(${JSON.stringify(card('fixture/firewall:latest'))})?.querySelector('b').textContent`),'测试 PC','renamed device moves into the PC category');
    await openImages();await click('.image-entry[data-image="fixture/firewall:latest"] .image-settings');
    await input('#edit-image-template','');await click('#save-image-settings');await wait('!document.querySelector("#image-edit-form")');
    await click('#close-images');await wait(`document.querySelectorAll('.device-card').length===${hostCount}`);
    assert.equal(await evaluate(`document.querySelectorAll(${JSON.stringify(card('fixture/firewall:latest'))}).length`),0,'unbinding removes only its own card');
    assert.ok(await evaluate('!!document.querySelector(".topology-node[data-node=fw1]")'),'library changes preserve existing canvas devices');
    await openImages();await click('.image-entry[data-image="fixture/firewall:latest"] .image-delete');
    await wait(`!document.querySelector('.image-entry[data-image="fixture/firewall:latest"]')`);await jobDone();await click('#close-images');
    await evaluate('window.__libraryBeforeReload=true');
    await send('Page.reload');await wait('!window.__libraryBeforeReload && !!document.querySelector("#library-home") && !document.querySelector("#access-dialog")?.open');
    await click('[data-category=router]');
    await wait('document.querySelectorAll(".device-card").length===60');
    await expandAll();
    assert.equal(await evaluate(`document.querySelectorAll(${JSON.stringify(card('alpine/frr:latest'))}).length`),0,'deleted default stays absent after reload across all pages');
    assert.equal(await evaluate('document.querySelectorAll(".device-card").length'),routerCount-1);
    await click('[data-category=host]');
    assert.equal(await evaluate(`document.querySelectorAll(${JSON.stringify(card('fixture/firewall:latest'))}).length`),0,'deleted imported image stays absent');
    await click('[data-category=router]');await wait('document.querySelectorAll(".device-card").length===60');
    await send('Emulation.setDeviceMetricsOverride',{width:1000,height:768,deviceScaleFactor:1,mobile:false});
    await wait('innerWidth===1000');
    assert.equal(await evaluate('document.documentElement.scrollWidth > innerWidth'),false);
    assert.equal(await evaluate('document.documentElement.scrollHeight > innerHeight'),false);
    assert.equal(await evaluate('new Set(Array.from(document.querySelectorAll("[data-category]")).map(e=>e.getBoundingClientRect().top)).size'),1);
    assert.ok(await evaluate('Array.from(document.querySelectorAll("[data-category]")).every(e=>e.scrollWidth<=e.clientWidth)'),'category labels fit the narrow sidebar');
    const overlap=await evaluate('(()=>{const empty=document.querySelector("#empty-state").getBoundingClientRect(), controls=document.querySelector(".canvas-controls").getBoundingClientRect(), footer=document.querySelector(".canvas-footer").getBoundingClientRect();return {top:empty.top,bottom:empty.bottom,controls:controls.bottom,footer:footer.top}})()');
    assert.ok(overlap.top>overlap.controls && overlap.bottom<overlap.footer,'empty guidance clears the canvas controls and footer');
    await evaluate('document.querySelector("#panel-resize-handle").focus()');
    await send('Input.dispatchKeyEvent',{type:'keyDown',key:'End'});await send('Input.dispatchKeyEvent',{type:'keyUp',key:'End'});
    await wait('document.querySelector("#panel-body").getBoundingClientRect().height>=96');
    assert.ok(await evaluate('document.querySelector(".bottom-panel").getBoundingClientRect().bottom<=innerHeight+1'),'maximum output height includes the canvas margins');
    await shot('device-grid-1000.png');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({ok:true,checks:['horizontal categories; devices hidden until entry','two-column cards; complete pagination; fixed category navigation','no category search; back and keyboard navigation; narrow viewport','default image deletion removes sidebar card across all pages','firewall import and canvas device','type change moves card to PC','unbinding removes only its card','existing canvas preserved','deleted entries stay gone after reload'],screenshots:output},null,2));
  }catch(error){await shot('failed.png');throw error;}finally{ws.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
